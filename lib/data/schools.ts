/**
 * 語学学校 構造化データ
 *
 * 【大原則】Google Places のコンテンツ（名前/評価/評価数/写真/周辺情報/営業時間等）は
 * このファイルにもDBにも保存・キャッシュしない。保存してよいのは placeId（と、使う場合のみ lat/lng）だけ。
 * 本文は実行時に app/api/places/* 経由でPlaces APIから取得して表示する。
 *
 * placeId は scripts/resolve-place-ids.ts（開発時にローカル実行するスクリプト。管理APIやDBは無い）が
 * name + address から Places API (New) Text Search で解決し、このファイルへ書き戻す。
 * placeIdRefreshedAt が12か月を超えたレコードはリフレッシュ対象。
 */

/**
 * コース種別タグ（提案パイプラインのハード足切りに使う固定語彙）。
 * コース名の自由文は courses に別途持つ。
 */
export type CourseCategory =
  | "general_english"
  | "exam_preparation"
  | "business_english"
  | "academic_pathway";

/** 滞在オプションの形態タグ（複数可）。料金・提携名等の詳細は accommodationNote に持つ */
export type AccommodationOption = "dormitory" | "homestay" | "not_arranged";

/** 金額レンジ（教材費等、期間を伴わない一時金向け。cities.ts の MoneyRange とは別物で period を持たない） */
export interface FeeRange {
  currency: string;
  min: number;
  max: number;
}

export interface School {
  /** 安定ID（例: ilsc-sydney） */
  schoolSlug: string;
  country: string;
  city: string;
  name: string;
  /** 日本語表記の学校名 */
  nameJa?: string;
  /**
   * キャンパス住所。ホームステイ型（教師の自宅に滞在するスタイル）等、
   * 固定キャンパスを持たない学校は undefined とし、Places解決の対象外にする。
   */
  address?: string;
  placeId?: string;
  lat?: number;
  lng?: number;
  /** placeId をいつ解決/確認したか（ISO日付）。12か月超で要リフレッシュ */
  placeIdRefreshedAt?: string;

  /** コース種別タグ（機械フィルタ用。決まった語彙のみ） */
  courseCategories?: CourseCategory[];
  /** コース名の自由文一覧（表示用）。ハード足切りには courseCategories を使う */
  courses?: string[];

  /**
   * 入学時期についての自由記述（例: "一般英語=毎週入学可/ケンブリッジ=固定開講"）。
   * コースごとに毎週入学可・固定開講が混在する学校が多く、学校単位の1値には強制できないため
   * 自由記述で持つ（機械フィルタが必要になった場合は F 実装時に別途検討）。
   */
  intakeNote?: string;
  /** 開講日・時間帯・週時間数などの自由記述（構造化しきれない注記をそのまま保持する） */
  scheduleNote?: string;

  /** 滞在オプションの形態タグ（複数可）。機械フィルタ用 */
  accommodationOptions?: AccommodationOption[];
  /** 滞在オプションの料金・最低滞在週数・提携レジデンス名などの自由記述（詳細） */
  accommodationNote?: string;

  /** 大学・専門学校等への進学パスウェイ提携があるか */
  hasPathway?: boolean;
  /** 提携先や条件などの補足（自由記述） */
  pathwayNotes?: string;

  /**
   * 生徒の年齢層（例: "18〜25歳中心"、"幅広い"）。
   * 国・学校で表現が異なるため固定選択肢にせず自由記述で持つ。カルテの personality.learningStyle 等とのマッチングに使う。
   */
  ageRange?: string;
  /** 1クラスの平均人数 */
  classSizeAvg?: number;
  /** 1クラスの最大人数 */
  classSizeMax?: number;
  /** 平均/最大に機械的に分離できないクラス人数の注記（自由記述） */
  classSizeNote?: string;

  /** 週あたり授業料の目安レンジ。詳細・条件は tuitionWeeklyNote に持つ */
  tuitionWeekly?: FeeRange;
  /** 週あたり授業料の詳細自由記述（コース別の内訳、期間限定料金、非公式値の注記等） */
  tuitionWeeklyNote?: string;
  /** 入学金の目安レンジ。詳細・条件は enrollmentFeeNote に持つ */
  enrollmentFee?: FeeRange;
  /** 入学金の詳細自由記述（ビザ種別による違い等） */
  enrollmentFeeNote?: string;
  /** 教材費の目安レンジ。詳細・条件は materialFeeNote に持つ */
  materialFee?: FeeRange;
  /** 教材費の詳細自由記述（段階制の内訳、コース別の別料金等）。値を持たせる場合は source / fetchedAt とセットで必須（AIが数値を創作して埋めないこと） */
  materialFeeNote?: string;

  /** 日本人比率（自由記述。公式値が無い場合は非公式値＋出所の注記を含めてよい） */
  japaneseRatio?: string;
  /** 生徒総数（自由記述。定員か在籍実数かの定義差が大きいため数値型にしない） */
  totalStudents?: string;
  /** 国籍多様性（上位国籍・比率等の自由記述） */
  nationalityDiversity?: string;
  /** 対応レベル（入学基準・レベル数等の自由記述） */
  levels?: string;
  /** 認定情報（CRICOS/RTO/NEAS/English Australia 等の自由記述） */
  accreditation?: string;

  /** 返金規定（自由記述）。ハード足切りには使わず、表示・エージェントへの引き継ぎ・注意喚起用 */
  refundPolicy?: string;

  /** 特徴タグ（softHints等のフィット指標に使う自由文タグ） */
  tags?: string[];

  /** 学費レンジ等、変動値の出所（機関名）。値を持たせる場合は fetchedAt とセットで必須 */
  source?: string;
  /** 根拠URL（複数可） */
  sourceUrl?: string[];
  /** 出所情報の取得日（ISO日付、または "2026-07" のような年月の粒度） */
  fetchedAt?: string;

  notes?: string;
}

